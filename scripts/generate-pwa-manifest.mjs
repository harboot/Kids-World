import { readFile, readdir, writeFile } from 'node:fs/promises';
import { posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateAreaRegistry } from '../core/area-registry.js';
import { sha256, validateManifest, versionFor } from '../pwa/release.js';
import { readAreaSources } from './generate-area-stats.mjs';
import { moduleDependencies, staticMetadata } from './pwa-dependencies.mjs';

const root = new URL('../', import.meta.url);
const roots = ['areas', 'assets', 'core', 'pwa', 'vendor'];
const catalogPath = 'area-catalog.js';
const entryFiles = ['area-stats.json', 'game.js', 'index.html', 'manifest.webmanifest', 'snow.html', 'stats.html', 'style.css'];
const developmentDirs = new Set(['docs', 'test', 'tests', '__tests__', 'node_modules']);
const developmentFile = /\.(?:md|markdown|map)$|\.(?:test|spec)\.[cm]?js$/i;

async function scan(directory) {
  const entries = await readdir(new URL(directory, root), { withFileTypes: true });
  const files = await Promise.all(entries.map(entry => {
    if (entry.name.startsWith('.')) return [];
    const path = directory + '/' + entry.name;
    if (entry.isDirectory()) return developmentDirs.has(entry.name) ? [] : scan(path);
    if (entry.isFile()) return developmentFile.test(entry.name) ? [] : path;
    throw new Error(`Unsupported release entry: ${path}`);
  }));
  return files.flat();
}

const areas = await readAreaSources(fileURLToPath(root));
const inventory = [...entryFiles, ...(await Promise.all(roots.map(scan))).flat()].sort();
const sources = new Map(await Promise.all(inventory.map(async path => [path, await readFile(new URL(path, root))])));
const metadata = {};
const registry = {};
const mandatory = new Set(inventory.filter(path => !path.startsWith('areas/')));
const optional = new Set();
const owners = new Set();

for (const { id, visibility, entry, directory, metadataPath } of areas) {
  if (owners.has(directory) || !entry.startsWith(directory + '/') || metadataPath !== posix.join(directory, 'metadata.js') ||
      !sources.has(entry) || !sources.has(metadataPath)) {
    throw new Error(`Could not verify release files owned by area "${id}"`);
  }
  owners.add(directory);
  const show = visibility === 'Public';
  const definition = staticMetadata(sources.get(metadataPath).toString('utf8'), metadataPath);
  Object.defineProperty(metadata, id, { value: definition, enumerable: true });
  Object.defineProperty(registry, id, { value: { ...definition, show, loadModule() {} }, enumerable: true });
  for (const path of inventory) {
    if (path.startsWith(directory + '/')) (show ? mandatory : optional).add(path);
  }
  if (show) {
    const thumbnail = directory + '/' + posix.basename(directory) + '.jpg';
    if (!sources.has(thumbnail)) throw new Error(`Missing public thumbnail for area "${id}": ${thumbnail}`);
  }
}
validateAreaRegistry(registry);

const catalog = '// Generated by scripts/generate-pwa-manifest.mjs from area metadata.\n' +
  'export const areaMetadata = ' + JSON.stringify(metadata, null, 2) + ';\n';
sources.set(catalogPath, new TextEncoder().encode(catalog));
mandatory.add(catalogPath);

const graph = new Map();
function expand(seeds) {
  // Iteration includes paths appended by transitive dependencies.
  for (const path of seeds) {
    if (!/\.[cm]?js$/i.test(path)) continue;
    if (!graph.has(path)) {
      const dependencies = moduleDependencies(new TextDecoder().decode(sources.get(path)), path, areas);
      for (const dependency of dependencies) {
        if (!sources.has(dependency)) throw new Error(`Missing release dependency ${dependency} referenced by ${path}`);
      }
      graph.set(path, dependencies);
    }
    for (const dependency of graph.get(path)) seeds.add(dependency);
  }
}

expand(mandatory);
expand(optional);
for (const path of mandatory) optional.delete(path);

async function revisions(paths) {
  return Promise.all([...paths].sort().map(async path => ({
    path: './' + path,
    revision: await sha256(sources.get(path)),
  })));
}

const [files, onDemandFiles] = await Promise.all([revisions(mandatory), revisions(optional)]);
const version = await versionFor(files, onDemandFiles);
const release = await validateManifest({ version, files, onDemandFiles });
const outputs = {
  [catalogPath]: catalog,
  'version.json': JSON.stringify(release, null, 2) + '\n',
  'sw.js': `// Generated by scripts/generate-pwa-manifest.mjs for release ${version}.\nimport './pwa/worker.js';\n`,
};

for (const [path, content] of Object.entries(outputs)) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8').catch(error => {
      if (error.code !== 'ENOENT') throw error;
    }) !== content) {
      throw new Error(`${path} is out of date. Run node scripts/generate-pwa-manifest.mjs`);
    }
  } else {
    await writeFile(url, content);
  }
}
console.log(`Kids World release ${version.slice(0, 12)} (${files.length} precached, ${onDemandFiles.length} on demand)`);
