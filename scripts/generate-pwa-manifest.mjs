import { readFile, readdir, writeFile } from 'node:fs/promises';
import { sha256, validateManifest, versionFor } from '../pwa/release.js';

const root = new URL('../', import.meta.url);
const roots = ['areas', 'assets', 'core', 'pwa', 'vendor'];
const entryFiles = ['game.js', 'index.html', 'manifest.webmanifest', 'snow.html', 'style.css'];

async function scan(directory) {
  const entries = await readdir(new URL(directory, root), { withFileTypes: true });
  const files = await Promise.all(entries.filter(entry => !entry.name.startsWith('.')).map(entry => {
    const path = directory + '/' + entry.name;
    if (entry.isDirectory()) return scan(path);
    if (entry.isFile()) return path;
    throw new Error(`Unsupported release entry: ${path}`);
  }));
  return files.flat();
}

const paths = [...entryFiles, ...(await Promise.all(roots.map(scan))).flat()].sort();
const files = await Promise.all(paths.map(async path => ({
  path: './' + path,
  revision: await sha256(await readFile(new URL(path, root))),
})));
const version = await versionFor(files);
const release = await validateManifest({ version, files });
const outputs = {
  'version.json': JSON.stringify(release, null, 2) + '\n',
  'sw.js': `// Generated by scripts/generate-pwa-manifest.mjs for release ${version}.\nimport './pwa/worker.js';\n`,
};

for (const [path, content] of Object.entries(outputs)) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== content) {
      throw new Error(`${path} is out of date. Run node scripts/generate-pwa-manifest.mjs`);
    }
  } else {
    await writeFile(url, content);
  }
}
console.log(`Kids World release ${version.slice(0, 12)} (${files.length} files)`);
