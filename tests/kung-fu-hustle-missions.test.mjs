import assert from 'node:assert/strict';
import { test } from 'node:test';
import * as THREE from '../vendor/three.module.min.js';
import kungFu from '../areas/kung-fu-hustle/index.js';
import { wingX } from '../areas/kung-fu-hustle/layout.js';
import { cooliePosition } from '../areas/kung-fu-hustle/coolie.js';
import { tailorPosition } from '../areas/kung-fu-hustle/tailor.js';
import { beastPosition } from '../areas/kung-fu-hustle/the-beast.js';
import { EYE_HEIGHT } from '../core/player.js';
import { normalizeMissionStatus } from '../core/missions.js';

test('all ten Kung Fu Hustle encounters count once, remain replayable, and reset per visit',()=>{
  const scene=new THREE.Scene(),camera=new THREE.PerspectiveCamera(),viewmodel=new THREE.Group();
  let completed=0,recorded=false;const messages=[];
  const area=kungFu.load({THREE,scene,camera,viewmodel,completeLevel(id){assert.equal(id,'kung-fu-hustle');completed++;recorded=true;},isLevelComplete:()=>recorded,notify:m=>messages.push(m)});
  scene.updateMatrixWorld(true);
  const status=()=>normalizeMissionStatus(area.missionStatus);
  const done=id=>status().missions.find(m=>m.id===id).complete;
  const tick=(p,n=35)=>{for(let i=0;i<n;i++)area.update(.1,p);};
  const far={x:0,y:EYE_HEIGHT,z:18.2};
  const ground=(p,dx=0,dz=0)=>({x:p.x+dx,y:EYE_HEIGHT,z:p.z+dz});
  assert.equal(status().missions.length,10);assert.equal(status().completed,0);
  tick({...ground(cooliePosition,0,2),y:EYE_HEIGHT+3.25});assert.equal(done('coolie'),false);
  tick(ground(cooliePosition,0,2));assert.ok(done('coolie'));
  tick(ground(tailorPosition,-2,0));assert.ok(done('tailor'));
  tick(ground(beastPosition,0,2));assert.ok(done('beast'));
  tick({x:wingX(-1,-14,5.76),z:5.76,y:EYE_HEIGHT+9.75});assert.ok(done('landlady'));
  const act=(label,id,seconds)=>{
    const t=area.interactions.find(t=>t.label===label);
    const p={x:t.x-.9,z:t.z,y:label==='Play Music'?EYE_HEIGHT+6.5:EYE_HEIGHT};
    tick(p,10);assert.ok(t.active);t.act();assert.equal(done(id),false);
    area.update(.1,p);assert.equal(done(id),false);
    tick(p,Math.ceil(seconds*10));assert.ok(done(id),id);
  };
  act('Draw Water','sauce',8);act('Take Steamed Bun','donut',4);
  act('Lets Dancing','dance',10);act('Play Music','harpists',10);act('Buy Lollipop','fong',4);
  assert.equal(status().completed,9);assert.equal(completed,0);
  const book=area.interactions.find(t=>t.label==='Open Book');
  book.act({});tick(far);assert.equal(done('book'),false);
  book.act({guideCamera:()=>()=>{}});assert.equal(done('book'),false);
  tick(far,200);assert.equal(status().completed,10);assert.equal(completed,1);
  assert.equal(status().hint,'Kung Fu Hustle complete!');
  const sauce=area.interactions.find(t=>t.label==='Draw Water');
  sauce.act();tick(far,85);assert.equal(status().completed,10);assert.equal(completed,1);
  assert.equal(messages.filter(m=>m==='Kung Fu Hustle complete!').length,1);
  area.reset();assert.equal(status().completed,0);
  sauce.act();area.update(.2,far);area.reset();tick(far,85);assert.equal(status().completed,0);
  area.unload();assert.equal(status().completed,0);
});
